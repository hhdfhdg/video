def export_json(path):
    data = {
        "duration": DURATION,
        "fps": FPS,
        "width": WIDTH,
        "height": HEIGHT,
        "lines": [
            {"id": i, "start": s, "window": w, "text": t, "whisper": wh}
            for (i, s, w, t, wh) in LINES
        ],
        "subtitles": [{"start": a, "end": b, "text": c} for (a, b, c) in SUBTITLES],
    }
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    return path


