export const BUILTIN_NAMES = BUILTIN_SKILLS.map((s) => s.name);

/* ---------- имена, проверка, разбор файлов ---------- */
const TRANSLIT = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i", й: "y", к: "k", л: "l", м: "m",
  н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "ts", ч: "ch", ш: "sh", щ: "sch",
  ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

/** Приводит имя к виду kebab-case латиницей. Кириллица транслитерируется. */
export function slugifySkillName(raw) {
  const lowered = String(raw ?? "").trim().toLowerCase();
  let out = "";
  for (const ch of lowered) out += TRANSLIT[ch] ?? ch;
  return out
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48)
    .replace(/-+$/g, "");
}

/** Разбирает SKILL.md: необязательный frontmatter (name, description) и тело. */
export function parseSkillMd(text) {
  const src = String(text ?? "").replace(/^﻿/, "").replace(/\r\n/g, "\n");
  const m = src.match(/^---\n([\s\S]*?)\n---[ \t]*(?:\n|$)/);
  if (!m) return { name: "", description: "", instructions: src.trim() };
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([A-Za-z_-]+)\s*:\s*(.*)$/);
    if (!kv) continue;
    let value = kv[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    meta[kv[1].toLowerCase()] = value;
  }
  return {
    name: meta.name || "",
    description: meta.description || "",
    instructions: src.slice(m[0].length).trim(),
  };
}

/** SKILL.md с frontmatter, совместимый с форматом скилов Claude. */
export function skillToMd(skill) {
  const description = String(skill.description || "").replace(/\s*\n\s*/g, " ").trim();
  return `---\nname: ${skill.name}\ndescription: ${description}\n---\n\n${String(skill.instructions || "").trim()}\n`;
}

/**
 * Проверка и приведение скила к виду, который можно хранить.
 * Возвращает { ok: true, skill } или { ok: false, error }.
 */
export function normalizeSkill(raw) {
  if (!raw || typeof raw !== "object") return { ok: false, error: "Скил должен быть объектом." };
  let instructions = typeof raw.instructions === "string" ? raw.instructions : "";
  let name = raw.name;
  let description = raw.description;

  // Модель иногда кладёт в instructions весь SKILL.md вместе с frontmatter — достаём оттуда недостающее.
  if (/^\s*---\n/.test(instructions)) {
    const parsed = parseSkillMd(instructions);
    instructions = parsed.instructions;
    if (!name) name = parsed.name;
    if (!description) description = parsed.description;
  }

  const slug = slugifySkillName(name);
  if (!SKILL_NAME_RE.test(slug)) {
    return { ok: false, error: "Некорректное имя скила: нужны латинские буквы, цифры и дефисы, до 48 знаков (например, meeting-notes)." };
  }
  const desc = typeof description === "string" ? description.replace(/\s+/g, " ").trim() : "";
  if (!desc) return { ok: false, error: "Нужно описание: что делает скил и когда его применять." };
  const body = instructions.trim();
  if (body.length < MIN_SKILL_INSTRUCTIONS) return { ok: false, error: "Инструкции слишком короткие." };
  if (body.length > MAX_SKILL_INSTRUCTIONS) {
    return { ok: false, error: `Инструкции слишком длинные (лимит ${MAX_SKILL_INSTRUCTIONS} символов).` };
  }
  return {
    ok: true,
    skill: { name: slug, description: desc.slice(0, MAX_SKILL_DESCRIPTION), instructions: body },
  };
}

/** Все скилы: встроенные и пользовательские. Пользовательский с занятым именем игнорируется. */
export function allSkills(userSkills = []) {
  const taken = new Set(BUILTIN_NAMES);
  const out = BUILTIN_SKILLS.map((s) => ({ ...s, builtin: true }));
  for (const s of userSkills) {
    if (!s || taken.has(s.name)) continue;
    taken.add(s.name);
    out.push({ ...s, builtin: false });
  }
  return out;
}

/** Включённые скилы. off — словарь «имя → true» для выключенных. */
export function enabledSkills(userSkills = [], off = {}) {
  return allSkills(userSkills).filter((s) => !off[s.name]);
}

